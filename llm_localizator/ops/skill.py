"""``llm-localizator skill install|check``: task skills for agents in a consumer repo (ADR-121, ADR-162).

Writes one Claude skill per task under ``.claude/skills/<name>/SKILL.md``:

* ``llm-localizator``: the hard rules (ask-first, stamps, cost), and which task skill to use;
* ``l10n-wire-strings``, ``l10n-add-language``, ``l10n-review``, ``l10n-release``:
  short recipes with exact commands and a "done when".

Sources live in ``help/skills/*.md`` (frontmatter included). Each is short, so it loads
quickly and triggers on a clear "use when"; the full, version-matched guide stays one
command away (``llm-localizator help agent``). Like the web runtime (ADR-118), the files
are ours: ``install`` refuses to replace a file it did not write unless forced, and
``check`` reports drift per skill. Only run on an explicit command (the guide's rule 1).
"""

from __future__ import annotations

import hashlib
from pathlib import Path

from ..help import HELP_DIR
from ..projects import ProjectConfig
from .types import OpResult

__all__ = ["op_skill", "skill_text", "skill_names", "SKILL_RELPATH", "SKILL_ACTIONS", "SKILLS_DIR"]

SKILLS_DIR = HELP_DIR / "skills"
CORE_SKILL = "llm-localizator"
SKILL_RELPATH = Path(".claude") / "skills" / CORE_SKILL / "SKILL.md"
SKILL_ACTIONS = ("install", "check")
_MARKER = "<!-- generated by llm-localizator skill install; do not edit, rerun it -->"


def skill_names() -> list[str]:
    """Packaged skills, core first."""
    names = sorted(p.stem for p in SKILLS_DIR.glob("*.md"))
    return sorted(names, key=lambda n: (n != CORE_SKILL, n))


def skill_text(name: str = CORE_SKILL) -> str:
    """The installed file: the packaged source with the ownership marker after its frontmatter."""
    raw = (SKILLS_DIR / f"{name}.md").read_text(encoding="utf-8").replace("\r\n", "\n")
    if not raw.startswith("---\n"):
        raise ValueError(f"skill {name!r} has no frontmatter")
    end = raw.index("\n---\n", 4) + len("\n---\n")
    front, body = raw[:end], raw[end:].lstrip("\n")
    digest = hashlib.sha256(raw.encode("utf-8")).hexdigest()[:12]
    return f"{front}\n{_MARKER}\n<!-- source sha {digest} -->\n\n{body}"


def _relpath(name: str) -> Path:
    return Path(".claude") / "skills" / name / "SKILL.md"


def _state(target: Path, wanted: str) -> str:
    if not target.is_file():
        return "missing"
    current = target.read_text(encoding="utf-8")
    if _MARKER not in current:
        return "foreign"
    return "current" if current.replace("\r\n", "\n") == wanted else "outdated"


_CHECK_MSG = {
    "current": "{rel}: up to date",
    "missing": "{rel}: not installed (llm-localizator skill install {project})",
    "foreign": "{rel}: exists but was not written by llm-localizator",
    "outdated": "{rel}: older than the packaged skill (llm-localizator skill install)",
}


def op_skill(cfg: ProjectConfig, action: str, *, force: bool = False) -> OpResult:
    command = f"skill {action}"
    if action not in SKILL_ACTIONS:
        return OpResult(ok=False, exit_code=2, command=command,
                        summary=f"unknown action {action!r} ({'|'.join(SKILL_ACTIONS)})")
    root = Path(cfg.root)
    rows: list[dict] = []
    lines: list[str] = []
    for name in skill_names():
        rel = _relpath(name)
        wanted = skill_text(name)
        target = root / rel
        state = _state(target, wanted)
        row = {"name": name, "path": rel.as_posix(), "state": state}
        if action == "check":
            lines.append(_CHECK_MSG[state].format(rel=rel.as_posix(), project=cfg.name))
        elif state == "current":
            lines.append(f"{rel.as_posix()}: already up to date")
        elif state == "foreign" and not force:
            lines.append(f"{rel.as_posix()}: exists and was not written by llm-localizator; pass --force")
            row["skipped"] = True
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(wanted, encoding="utf-8")
            lines.append(f"{rel.as_posix()}: written (was {state})")
            row["state"] = "current"
        rows.append(row)

    current = sum(1 for r in rows if r["state"] == "current")
    data = {"skills": rows,
            # Back-compat with the single-skill result (ADR-121): the core skill's path/state.
            "path": rows[0]["path"], "state": rows[0]["state"]}
    if action == "check":
        ok = current == len(rows)
        summary = (f"all {len(rows)} skills up to date" if ok
                   else f"{len(rows) - current} of {len(rows)} skills need install")
        return OpResult(ok=ok, exit_code=0 if ok else 1, command=command,
                        summary=summary, lines=lines, data=data)
    skipped = [r["name"] for r in rows if r.get("skipped")]
    if skipped:
        return OpResult(ok=False, exit_code=1, command=command,
                        summary=f"{len(skipped)} skill file(s) not ours; pass --force: {', '.join(skipped)}",
                        lines=lines, data=data)
    return OpResult(ok=True, exit_code=0, command=command,
                    summary=f"{len(rows)} skills installed under .claude/skills/", lines=lines, data=data)
