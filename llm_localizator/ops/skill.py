"""``llm-localizator skill install|check``: the agent guide as a Claude skill in a consumer (ADR-121).

Writes ``.claude/skills/llm-localizator/SKILL.md``: skill frontmatter plus the packaged
``help/agent.md``, so an agent opened in the consumer repo loads the rules without
being pointed at them. Like the web runtime (ADR-118), the file is ours: ``install``
refuses to replace a file it did not write unless forced, and ``check`` reports drift.
Only run on an explicit command (the agent guide's rule 1).
"""

from __future__ import annotations

import hashlib
from pathlib import Path

from ..help import guide_text
from ..projects import ProjectConfig
from .types import OpResult

__all__ = ["op_skill", "skill_text", "SKILL_RELPATH", "SKILL_ACTIONS"]

SKILL_RELPATH = Path(".claude") / "skills" / "llm-localizator" / "SKILL.md"
SKILL_ACTIONS = ("install", "check")
_MARKER = "<!-- generated by llm-localizator skill install; do not edit, rerun it -->"


def skill_text() -> str:
    body = guide_text("agent")
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()[:12]
    return (
        "---\n"
        "name: llm-localizator\n"
        "description: Rules and recipes for localizing this project with llm-localizator: "
        "choosing an approach, wiring UI text (i18n.t, data-i18n), the hardcoded-text loop "
        "(agent-hardcoded, check-keys, en-XX crawl), translation checks, and when to ask the "
        "user first. Read before editing catalogues or wiring strings.\n"
        "---\n\n"
        f"{_MARKER}\n<!-- source sha {digest} -->\n\n{body}"
    )


def op_skill(cfg: ProjectConfig, action: str, *, force: bool = False) -> OpResult:
    command = f"skill {action}"
    if action not in SKILL_ACTIONS:
        return OpResult(ok=False, exit_code=2, command=command,
                        summary=f"unknown action {action!r} ({'|'.join(SKILL_ACTIONS)})")
    target = Path(cfg.root) / SKILL_RELPATH
    rel = SKILL_RELPATH.as_posix()
    wanted = skill_text()
    current = target.read_text(encoding="utf-8") if target.is_file() else None
    if current is None:
        state = "missing"
    elif _MARKER not in current:
        state = "foreign"
    elif current.replace("\r\n", "\n") == wanted:
        state = "current"
    else:
        state = "outdated"
    data = {"path": rel, "state": state}
    if action == "check":
        messages = {
            "current": f"{rel}: up to date",
            "missing": f"{rel}: not installed (llm-localizator skill install {cfg.name})",
            "foreign": f"{rel}: exists but was not written by llm-localizator",
            "outdated": f"{rel}: older than the packaged agent guide (llm-localizator skill install)",
        }
        ok = state == "current"
        return OpResult(ok=ok, exit_code=0 if ok else 1, command=command,
                        summary=messages[state], data=data)
    if state == "foreign" and not force:
        return OpResult(ok=False, exit_code=1, command=command,
                        summary=f"{rel} exists and was not written by llm-localizator; pass --force",
                        data=data)
    if state == "current":
        return OpResult(ok=True, exit_code=0, command=command,
                        summary=f"{rel}: already up to date", data=data)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(wanted, encoding="utf-8")
    data["state"] = "current"
    return OpResult(ok=True, exit_code=0, command=command,
                    summary=f"{rel}: written (was {state})", data=data)
