"""Language-neutral conformance matrix for the hardcoded-text scanner.

Every language answers the same questions. A category is either a string a person should see
(``ui``: the scanner must report it) or one it must stay silent about (``not_ui``, ``routed``).
The snippets need not compile: the scanner is lexical. ``@key@`` is replaced by the category phrase.
"""

