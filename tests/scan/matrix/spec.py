# Languages with no scanner by design: the report must say so instead of staying silent.
REPORTED_ONLY: dict[str, tuple[str, str]] = {
    "clojure": ("matrix.clj", '(def msg "Please sign in to continue")'),
    "groovy": ("matrix.groovy", 'def msg = "Please sign in to continue"'),
}


def render(lang: str) -> str:
    """One source file holding every category, blank-line separated, phrases substituted."""
    _name, snippets = LANGS[lang]
    blocks = []
    for cat, body in snippets.items():
        text = body
        for key, (_intent, phrase) in CATEGORIES.items():
            text = text.replace(f"@{key}@", phrase)
        blocks.append(text)
    return "\n\n".join(blocks) + "\n"
